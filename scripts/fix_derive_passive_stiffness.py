"""Derive patch passive_stiffness_v1: joint springs that bring total passive stiffness to measured values.

Stiffness targets carry an evidence label (measured, assumed in a published model, or estimated by analogy).
Measured stiffness in relaxed subjects already includes passive muscle, so adding it on top of the model's muscle
passive force would count it twice. For each covered joint:

    model_muscle_k = -d(passive muscle torque)/dq at qpos0 (central difference, all activations zero)
    joint spring   = max(0, target_mean - model_muscle_k)

The measured value is direction dependent; a MuJoCo joint spring is linear, so the mean of the directions is used.
Writes data/patches/passive_stiffness_v1.yaml and reports/fixes/passive_stiffness_derivation.json.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import mujoco
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from simulation.muscles import moment_arm_matrix
from simulation.patches import build_biohand_model

SOURCE = "data/sources/passive_joint_stiffness.yaml"
BASE_PATCHES = ("wrist_rom_v1", "muscle_fixes_v1", "limit_stiffness_v1", "thumb_intrinsics_v1")
DELTA_RAD = 0.02


def passive_torque(m: mujoco.MjModel, d: mujoco.MjData, dof: int) -> float:
    """Torque on one joint from all muscles at zero activation, N m."""
    mujoco.mj_forward(m, d)
    return float(moment_arm_matrix(m, d)[:, dof] @ -d.actuator_force)


def muscle_stiffness(m: mujoco.MjModel, joint: str) -> float:
    j = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, joint)
    if j < 0:
        raise KeyError(joint)
    d = mujoco.MjData(m)
    values = []
    for sign in (1.0, -1.0):
        d.qpos[:] = m.qpos0
        d.qpos[m.jnt_qposadr[j]] = m.qpos0[m.jnt_qposadr[j]] + sign * DELTA_RAD
        values.append(passive_torque(m, d, int(m.jnt_dofadr[j])))
    return -(values[0] - values[1]) / (2 * DELTA_RAD)


def main() -> None:
    (ROOT / "reports" / "fixes").mkdir(parents=True, exist_ok=True)
    src = yaml.safe_load((ROOT / SOURCE).read_text(encoding="utf-8"))
    m = build_biohand_model(BASE_PATCHES).model
    changes: list[dict[str, Any]] = []
    rows = {}
    for joint, row in src["joints"].items():
        measured = float(np.mean(row["values_Nm_per_rad"]))
        k_muscle = muscle_stiffness(m, joint)
        k_joint = max(0.0, measured - k_muscle)
        rows[joint] = {"evidence": row["evidence"], "target_total": round(measured, 6),
                       "model_muscle_k": round(k_muscle, 4), "joint_spring": round(k_joint, 4)}
        changes.append({"field": "joint_stiffness", "joint": joint, "source_file": SOURCE, "source": row["source"],
                        "evidence": row["evidence"],
                        "target_total_Nm_per_rad": round(measured, 6), "model_muscle_k_Nm_per_rad": round(k_muscle, 4),
                        "stiffness_Nm_per_rad": round(k_joint, 4)})
    patch = {
        "patch_id": "passive_stiffness_v1", "version": 1, "status": "provisional",
        "classification": "target total stiffness minus model muscle stiffness, by rule; linear around neutral",
        "approved_by": "project owner ('fix this', 2026-11-01)",
        "rationale": "Gap J3 / finding J3': upstream joints have k = 0 and the unbraced hand droops at rest.",
        "evidence": ["reports/fixes/passive_stiffness_derivation.json", SOURCE],
        "limitations": "Direction dependence and cross-coupling are not modelled. Thumb values are assumed, not "
                       "measured; MCP 3-5 are estimated from the index. MCP abduction, PIP and DIP keep k = 0.",
        "changes": changes,
    }
    header = "# GENERATED by scripts/fix_derive_passive_stiffness.py - do not edit numbers by hand.\n"
    text = header + yaml.safe_dump(patch, sort_keys=False, allow_unicode=True, width=110)
    (ROOT / "data" / "patches" / "passive_stiffness_v1.yaml").write_text(text, encoding="utf-8")
    (ROOT / "reports" / "fixes" / "passive_stiffness_derivation.json").write_text(
        json.dumps(rows, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(rows, indent=1))


if __name__ == "__main__":
    main()
