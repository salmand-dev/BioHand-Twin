GEN_NOTE = ("<!-- GENERATED by scripts/p2_generate_docs.py from the pinned MyoHand model, "
            "data/anatomy/glossary.yaml and reports/P1/osim_vs_myohand.json. Do not edit by hand. -->\n")
SOURCE_LINE = f"Model: MyoHand fragment, MyoSim `{MYOSIM_PINNED_COMMIT}`, MuJoCo {mujoco.__version__}.\n"
#: Suffix of mesh-geom node names in the GLB (blender/scripts/build_glb.py).
VISUAL_SUFFIX = "__visual"
FORCE_TOL_N = 0.5
RANGE_TOL_RAD = 1e-4


def deg(x: float) -> str:
    return f"{math.degrees(x):.1f}"


def fmt(v: float, nd: int = 4) -> str:
    return f"{v:.{nd}f}"


def provenance_tables() -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    path = ROOT / "reports" / "P1" / "osim_vs_myohand.json"
    if not path.is_file():
        return {}, {}
    comp = json.loads(path.read_text())
    joints = {j["myohand_joint"]: j for j in comp["2nd_hand_mass"]["joints"]}
    mobl = {a["myohand_actuator"]: a for a in comp["mobl_arms_bimanual"]["actuators"]}
    hand2 = {a["myohand_actuator"]: a for a in comp["2nd_hand_mass"]["actuators"]}
    acts: dict[str, dict[str, Any]] = {}
    for name, h in hand2.items():
        m = mobl.get(name, {})
        if m.get("osim_muscle"):
            src, ref = "MoBL-ARMS", m
        elif h.get("osim_muscle"):
            src, ref = "2nd-Hand", h
        else:
            acts[name] = {"class": "added", "source": "none in MoBL-ARMS or 2nd-Hand"}
            continue
        same = abs(ref["myohand_peak_force_N"] - ref["max_isometric_force"]) <= FORCE_TOL_N
        acts[name] = {"class": "inherited" if same else "modified", "source": src,
                      "source_value": ref["max_isometric_force"], "source_muscle": ref["osim_muscle"]}
    return joints, acts


def joints_doc(model: mujoco.MjModel, inv: dict[str, Any], g: Glossary,
               jprov: dict[str, dict[str, Any]], seg_of: dict[str, str],
               patched: mujoco.MjModel, patch_ids: tuple[str, ...]) -> str:
    out = [GEN_NOTE, "# Joints and Degrees of Freedom\n\n", SOURCE_LINE,
           ("\nAll joints are hinges. Values are stored in radians; degrees are for display only. "
           "The BioHand neutral pose is `model.qpos0` (all zeros, inside every range). "
           "This is the model's zero, **not** an anatomically defined neutral position.\n\n"
           "Positive direction is *derived from the model* (kinematic perturbation and muscle "
           "moment-arm signs, both verified by `tests/test_p2_anatomy.py`), at qpos0 only. "
           "Hinge rotation sense is constant over the range; muscle moment-arm signs over the range are P4.\n\n"
           f"**BioHand range** is the range of the BioHand reference model = upstream + patches "
           f"{', '.join(patch_ids)} (`data/patches/`). Upstream files are never modified.\n\n"),
           ("| # | Joint | Canonical name | Body (rigid segment) | + direction | Upstream range (deg) | "
           "Upstream range provenance | BioHand range (deg) | Damping N·m·s/rad |\n"
           "|---|---|---|---|---|---|---|---|---|\n")]
    for j in inv["joints"]:
        e = g.entry(j["name"])
        lo, hi = j["range_rad"]
        p = jprov.get(j["name"])
        if p and p.get("osim_range_rad"):
            prov = ("inherited (2nd-Hand)" if p.get("range_identical_1e-4") else
                    f"**modified** (2nd-Hand: {deg(p['osim_range_rad'][0])}…{deg(p['osim_range_rad'][1])})")
        else:
            prov = "unknown"
        status = "" if e["status"] == "derived" else " ⚠ muscle-only"
        plo, phi = patched.jnt_range[j["id"]]
        biohand = (f"{deg(plo)} … {deg(phi)}" if np.allclose([plo, phi], [lo, hi])
                   else f"**{deg(plo)} … {deg(phi)}** (patched)")
        if j["name"] == "deviation_r":
            prov += " — but sign **inverted** vs MoBL (gap T10)"
        out.append(f"| {j['id']} | `{j['name']}` | {e['canonical_name']} | `{j['body']}` (`{seg_of[j['body']]}`) | "
                   f"{e['positive_direction']}{status} | {deg(lo)} … {deg(hi)} | {prov} | {biohand} | "
                   f"{j['damping_Nms_per_rad']:g} |\n")
    out.append("\nAll joints: stiffness 0, armature 1e-4 kg·m², frictionloss 0 (upstream values).\n\n"
               "## Notes per joint\n\n")
    for e in g.entries("joints"):
        if e.get("notes"):
            out.append(f"- `{e['model_name']}`: {e['notes']}\n")
    out.append("\n## Joint axes\n\nAxis in the body frame, and in the world frame at qpos0.\n\n"
               "| Joint | Axis (body) | Axis (world, qpos0) | Anchor (body, m) |\n|---|---|---|---|\n")
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    for j in range(model.njnt):
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, j)
        b = model.jnt_bodyid[j]
        world = data.xmat[b].reshape(3, 3) @ model.jnt_axis[j]
        out.append(f"| `{name}` | {np.round(model.jnt_axis[j], 4).tolist()} | {np.round(world, 4).tolist()} | "
                   f"{np.round(model.jnt_pos[j], 4).tolist()} |\n")
    return "".join(out)


def muscle_doc(inv: dict[str, Any], g: Glossary, aprov: dict[str, dict[str, Any]]) -> str:
    out = [GEN_NOTE, "# Muscle Model Specification\n\n", SOURCE_LINE, """
## Semantics as implemented

- Every actuator is a MuJoCo `muscle`: `dyntype=muscle` (first-order activation with separate activation and deactivation time constants), `gaintype=muscle` and `biastype=muscle` (MuJoCo's built-in normalised force–length, force–velocity and passive-force curves). The transmission is one spatial tendon.
- **Do not stack a second Hill model on top.** Force is computed by MuJoCo; BioHand reads `actuator_force`.
- Tendons are inextensible (stiffness 0). There is no pennation angle and no tendon slack length.
- `L0 = (lengthrange[1] - lengthrange[0]) / (range[1] - range[0])` is MuJoCo's length normalisation, **not an anatomical optimal fibre length**.
- Shared by all actuators (class defaults, **not muscle-specific**): `range` 0.75–1.05, `lmin` 0.5, `lmax` 1.6, `vmax` 1.5 L0/s, `fpmax` 1.3, `fvmax` 1.2, τ_act 0.01 s, τ_deact 0.04 s.
- Muscle-specific values: peak force `F_max` and `lengthrange` only.

## Provenance classes for F_max
- **inherited**: equals the source model's `max_isometric_force` within 0.5 N.
- **modified**: differs from the source.
- **added**: no source value.

Sources compared: MoBL-ARMS bimanual (extrinsic muscles) and 2nd-Hand (intrinsic muscles); see `reports/P1/osim_vs_myohand.json`. Note that the 2nd-Hand intrinsic values are themselves placeholders (gap T3).

| Actuator | Canonical name | Name status | F_max (N) | F_max provenance | lengthrange (m) | L0 (normalisation, m) | Spans joints at qpos0 |
|---|---|---|---|---|---|---|---|
"""]
    spans = {t["name"]: t["dL_dq_at_qpos0_m_per_rad"] for t in inv["tendons"]}
    for a in inv["actuators"]:
        e = g.entry(a["name"])
        p = aprov.get(a["name"], {"class": "unknown"})
        if p["class"] == "added":
            prov = "**added**"
        elif p["class"] == "unknown":
            prov = "unknown"
        else:
            prov = f"{p['class'] if p['class'] == 'inherited' else '**modified**'} ({p['source']} `{p['source_muscle']}` = {p['source_value']:g} N)"
        mp = a["mujoco_muscle_params"]
        lr = a["lengthrange_m"]
        j = ", ".join(k.removesuffix("_r") for k in spans[a["target"]])
        out.append(f"| `{a['name']}` | {e['canonical_name']} | {e['status']} | {mp['peak_active_force_N']:g} | {prov} | "
                   f"{fmt(lr[0])}–{fmt(lr[1])} | {fmt(a['derived_L0_equivalent_m']['value'])} | {j} |\n")
    out.append(
        "\n## Actions at the neutral pose (derived)\n\n"
        "Biomechanical moment arm r = −dL/dq (m/rad): with tension T ≥ 0 the joint torque is r·T, so r > 0 drives "
        "the joint in its glossary *positive direction*. Listed: joints with |r| ≥ 2 mm at qpos0, largest first. "
        "Derived from the model; not a literature statement. Moment-arm curves over the full range are in "
        "`reports/P4/moment_arm_curves.json`.\n\n| Actuator | Actions (r in mm) |\n|---|---|\n")
    jdir = {e["model_name"]: e for e in g.entries("joints")}
    for a in inv["actuators"]:
        acts = []
        for jn, dl in sorted(spans[a["target"]].items(), key=lambda kv: -abs(kv[1])):
            r = -dl
            if abs(r) < 2e-3:
                continue
            label = jdir[jn]["positive_direction"] if r > 0 else jdir[jn]["negative_direction"]
            acts.append(f"{jdir[jn]['canonical_name']}: **{label}** ({1000 * r:+.1f})")
        out.append(f"| `{a['name']}` | {'; '.join(acts) or '—'} |\n")
    out.append(
        "\n## Validity limits (P4)\n\n"
        "- **Muscle-path validity envelope.** Forces/torques are only claimed for wrist flexion −45…+45° and "
        "deviation −10…+10°: the intersection of the upstream-calibrated and BioHand ranges "
        "(`simulation.patches.muscle_validity_envelope`). Beyond it, upstream paths break or reverse (P4 report).\n"
        "- The tables above describe the **upstream** muscles. The BioHand reference model applies the muscle "
        "repairs listed below.\n")
    fixes = Patch.load("muscle_fixes_v1").data
    out.append("\n## BioHand muscle repairs (patch `muscle_fixes_v1`, status: "
               f"{fixes['status']})\n\n| Change | Target | Upstream | BioHand | Basis |\n|---|---|---|---|---|\n")
    for ch in fixes["changes"]:
        if ch["field"] == "actuator_force":
            out.append(f"| peak force | `{ch['actuator']}` | {ch['upstream_value_N']:g} N | {ch['patched_value_N']:g} N | "
                       f"source value ({ch['source_model']} `{ch['source_muscle']}`) |\n")
        elif ch["field"] == "tendon_remove_wrap":
            out.append(f"| path | `{ch['tendon']}` | via `{ch['remove']}` | sites only | consistent with converted "
                       "siblings RI3–RI5 (gap M7′) |\n")
        elif ch["field"] == "actuator_lengthrange":
            u, p = ch["upstream_value_m"], ch["patched_value_m"]
            out.append(f"| lengthrange | `{ch['actuator']}` | {fmt(u[0])}–{fmt(u[1])} m | {fmt(p[0])}–{fmt(p[1])} m | "
                       f"MuJoCo definition re-derived; {ch['reason']} |\n")
    agree = fixes["lengthrange_method"]["method_agreement_on_healthy_upstream_muscles"]
    out.append(f"\nDerivation check: on {agree['n_healthy']} healthy upstream muscles the same method reproduces the "
               f"upstream `lengthrange` with a median error of {agree['median_abs_mm']} mm "
               f"(90th percentile {agree['p90_abs_mm']} mm).\n")
    out.append("\n## Not represented\n\n")
    for e in g.entries("not_represented"):
        if e["structure_type"] in ("muscle", "tendon_network"):
            out.append(f"- {e['canonical_name']} (gap {e['gap_id']})\n")
    return "".join(out)


def mapping_doc(model: mujoco.MjModel, g: Glossary) -> str:
    out = [GEN_NOTE, "# Anatomical Mapping\n\n", SOURCE_LINE,
           ("\nCanonical names come from `data/anatomy/glossary.yaml`. Status `provisional` means a standard "
           "English term whose citation is still pending. `unresolved` names must carry an "
           "\"unverified\" badge in the UI.\n\n## Rigid segments (motion units)\n\n"
           "Only these units can move relative to each other. "
           "The UI contract is `simulation/ui_contract.py`.\n\n"
           "| Segment root | Parent segment | Joints (DoF) | Member bodies |\n|---|---|---|---|\n")]
    for s in rigid_segments(model):
        members = ", ".join(g.canonical(b) or f"`{b}`" for b in s.bodies)
        out.append(f"| `{s.root_body}` | {('`' + s.parent_segment + '`') if s.parent_segment else '— (world)'} | "
                   f"{', '.join(s.joints) or '—'} ({s.n_dof}) | {members} |\n")
    out.append("\n## Bodies\n\n| Model body | Canonical name | Representation | Status | Notes |\n|---|---|---|---|---|\n")
    for e in g.entries("bodies"):
        out.append(f"| `{e['model_name']}` | {e['canonical_name'] or '—'} | {e['representation']} | {e['status']} | "
                   f"{e.get('notes', '')} |\n")
    out.append("\n## Structures not represented in the model\n\n| Structure | Type | Gap |\n|---|---|---|\n")
    for e in g.entries("not_represented"):
        out.append(f"| {e['canonical_name']} | {e['structure_type']} | {e['gap_id']} |\n")
    return "".join(out)


def coordinate_doc(model: mujoco.MjModel) -> str:
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    f = hand_frame(model, data)
    rows = []
    for label, v in [("distal", f.distal), ("radial", f.radial), ("dorsal", f.dorsal)]:
        rows.append(f"| {label} | {np.round(v, 3).tolist()} | {np.round(mujoco_to_godot_pos(v), 3).tolist()} |\n")
    return "".join([GEN_NOTE, "# Coordinate System\n\n", SOURCE_LINE, """
## Frames

| Frame | Handedness | Up | Units | Quaternion order | Role |
|---|---|---|---|---|---|
| MuJoCo world | right | +Z (gravity (0, 0, −9.81)) | m, rad | (w, x, y, z) | **Simulation truth** |
| MuJoCo body frames | right | — | m | (w, x, y, z) | Joint axes, sites, inertia |
| Godot / glTF | right | +Y | m | (x, y, z, w) | Visualisation only |
| Blender | right | +Z | m | (w, x, y, z) | Asset preparation only |

## The one conversion (`biomechanics/frames.py`)

- Position: `(x, y, z)_MuJoCo → (x, z, −y)_Godot`. Matrix `C = [[1,0,0],[0,0,1],[0,−1,0]]`, which is −90° about +X with det = +1, so handedness is preserved.
- Orientation: `R_Godot = C · R_MuJoCo · Cᵀ`. In quaternions, `q_G = q_C ⊗ q_MJ ⊗ q_C*`, then reorder to (x, y, z, w).
- MuJoCo world positions written into Blender unchanged (both Z-up) are converted by Blender's glTF exporter (+Y up) to exactly the same result. `tests/test_visual_export.py` verifies this when the local GLB has been built.
- No other module may apply axis flips or sign changes.

## Hand orientation at the neutral pose (derived, qpos0)

Hand frame from landmark body origins (`simulation/kinematic_semantics.py`):
- distal = lunate → proximal phalanx III;
- radial = proximal phalanx V → II, orthogonalised;
- dorsal = distal × radial (right hand).

| Axis | MuJoCo world | Godot |
|---|---|---|
""", *rows, """
At qpos0 the forearm points roughly along world +X, the radial side faces roughly +Y, and the **dorsum faces roughly +Z (palm down)**. This orientation comes from the fixed shoulder "preview pose" baked in by the upstream builder (`hand.py`). It is not an anatomical position.

## Anatomical (ISB) frames

Not implemented. Adopting ISB wrist/hand recommendations (Wu et al. 2005) is planned for reporting only, after that paper is retrieved. MuJoCo joint coordinates remain the simulation truth.
"""])


def mapping_csv(model: mujoco.MjModel, g: Glossary, seg_of: dict[str, str]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["visual_node", "canonical_name", "mujoco_body", "rigid_segment", "source",
                "representation", "notes"])
    spec_files = {m.name: m.file for m in build_myohand("fragment").spec.meshes}
    meshdir = DEFAULT_MYOSIM_DIR / "myo_sim" / "models"
    for gid in range(model.ngeom):
        gname = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, gid)
        body = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, model.geom_bodyid[gid])
        e = g.entry(body)
        if model.geom_type[gid] == mujoco.mjtGeom.mjGEOM_MESH:
            mesh = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_MESH, model.geom_dataid[gid])
            rel = spec_files[mesh]
            digest = hashlib.sha256((meshdir / rel).read_bytes()).hexdigest()[:16]
            src = f"MyoSim {rel} sha256:{digest}"
            note = "" if gname == body else "geom name differs from body name (upstream naming)"
            rep = e["representation"]
        else:
            group = int(model.geom_group[gid])
            kind = {3: "tendon wrapping surface", 4: "collision proxy"}.get(group, f"group {group}")
            src, rep, note = "MyoSim primitive geom", "debug_only", kind
        node = f"{gname}{VISUAL_SUFFIX}" if model.geom_type[gid] == mujoco.mjtGeom.mjGEOM_MESH else gname
        w.writerow([node or f"<unnamed geom {gid}>", e["canonical_name"] or "", body, seg_of[body],
                    src, rep, note])
    return buf.getvalue()


def evidence_json(model: mujoco.MjModel) -> str:
    ev = joint_kinematic_evidence(model, model.qpos0.copy())
    return json.dumps({
        "model_commit": MYOSIM_PINNED_COMMIT,
        "method": "perturb joint by +0.1 rad at qpos0; displacement of tracked mesh centroid in hand frame "
                  "(distal, radial, dorsal) of the unperturbed pose; rotation of radial axis about distal",
        "joints": [e.__dict__ for e in ev],
    }, indent=1) + "\n"


def generate(out_root: Path) -> list[Path]:
    built = build_myohand("fragment")
    model = built.model
    inv = build_inventory(model, built.spec)
    g = Glossary.load()
    seg_of = segment_of_body(model)
    jprov, aprov = provenance_tables()
    patched_build = build_biohand_model()
    files = {
        "docs/JOINTS_AND_DOF.md": joints_doc(model, inv, g, jprov, seg_of,
                                             patched_build.model, patched_build.patches),
        "docs/MUSCLE_MODEL.md": muscle_doc(inv, g, aprov),
        "docs/ANATOMICAL_MAPPING.md": mapping_doc(model, g),
        "docs/COORDINATE_SYSTEM.md": coordinate_doc(model),
        "blender/visual_to_physics_mapping.csv": mapping_csv(model, g, seg_of),
        "reports/P2/joint_semantics_evidence.json": evidence_json(model),
    }
    written = []
    for rel, text in files.items():
        p = out_root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        written.append(p)
    return written


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT)
    for p in generate(ap.parse_args().out):
        print("wrote", p)


if __name__ == "__main__":
    main()
