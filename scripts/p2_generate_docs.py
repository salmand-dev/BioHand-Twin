"""Generate P2 specification documents and mappings from the model and glossary.

Deterministic: same model + glossary + P1 evidence -> byte-identical output (no
timestamps). tests/test_generated_docs.py fails if committed files drift.

Outputs (relative to --out, default: project root):
  docs/JOINTS_AND_DOF.md
  docs/MUSCLE_MODEL.md
  docs/ANATOMICAL_MAPPING.md
  docs/COORDINATE_SYSTEM.md
  blender/visual_to_physics_mapping.csv
  reports/P2/joint_semantics_evidence.json

Usage: .venv/Scripts/python.exe scripts/p2_generate_docs.py [--out DIR]
"""

